@dataclass(init=False)
class FunctionStmt(Stmt):
    name: str = ""
    ret: Expr | None = None
    items: List[Param]
    suite: SuiteStmt | None = None
    decorators: List[Expr]
    async_: bool = False
    signature: str = ""

    def __init__(
        self,
        name: str = "",
        ret: Expr | None = None,
        items: List[Param] | None = None,
        suite: SuiteStmt | None = None,
        decorators: List[Expr] | None = None,
        async_: bool = False,
        signature: str = "",
        **kwargs,
    ):
        # C++ source: codon/parser/ast/stmt.cpp:570
        super().__init__(**kwargs)
        self.items = [] if items is None else items
        self.name = name
        self.ret = ret
        self.suite = SuiteStmt.wrap(suite)
        self.decorators = [] if decorators is None else decorators
        self.async_ = async_
        self.signature = signature

    def get_signature(self):
        """A function signature that consists of generics and arguments in a S-expression form."""
        if not self.signature:
            self.signature = ":".join(
                "-" if p.type is None else str(p.type) for p in self.items
            )
        return self.signature

    def get_star_arg(self) -> int:
        return next(
            (
                index
                for index, p in enumerate(self.items)
                if p.name.startswith("*") and not p.name.startswith("**")
            ),
            len(self.items),
        )

    def get_kwstar_arg(self) -> int:
        return next(
            (index for index, p in enumerate(self.items) if p.name.startswith("**")),
            len(self.items),
        )

    def get_docstr(self) -> str:
        return get_docstring(self.suite)

    # Check if a function can be called with the given arguments.
    # See @c reorderNamedArgs for details.
    def get_non_inferrable_generics(self) -> Set[str]:
        class IdMatch(Visitor):
            def __init__(self, value):
                self.value = value

            def visit_IdExpr(self, i):
                return i.value == self.value

        def contains_id(expr, name):
            return IdMatch(name).accept(expr)

        result: Set[str] = set()
        for i in self.items:
            if i.is_generic() and i.default_value is None:
                inferrable = False
                for candidate in self.items:
                    if candidate.type and contains_id(candidate.type, i.name):
                        inferrable = True
                        break
                if self.ret and contains_id(self.ret, i.name):
                    inferrable = True
                if not inferrable:
                    result.add(i.name)
        return result

    def has_function_attr(self, attribute: str):
        if a := self.get(Attr.FunctionAttributes):
            return attribute in a


