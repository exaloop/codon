class ImportStmt(Stmt):
    """
    This node describes various kinds of import statements:
    - from from import what (as as)
    - import what (as as)
    - from c import what(args...) (-> ret) (as as)
    - from .(dots...)from import what (as as)
    """

    from_expr: Expr | None = None
    what: Expr | None = None
    # Function argument types for C imports.
    args: List[Param]
    # Function return type for C imports.
    ret: Expr | None = None
    as_: str = ""
    # Number of dots in a relative import (e.g. dots is 3 for "from ...foo").
    dots: int = 0
    # Set if this is a function C import (not variable import)
    is_function: bool = True

    def __init__(
        self,
        from_expr: Expr | None = None,
        what: Expr | None = None,
        args: List[Param] | None = None,
        ret: Expr | None = None,
        as_: str = "",
        dots: int = 0,
        is_function: bool = True,
        **kwargs,
    ):
        super().__init__(**kwargs)
        self.from_expr = from_expr
        self.what = what
        self.args = [] if args is None else args
        self.ret = ret
        self.as_ = as_
        self.dots = dots
        self.is_function = is_function
        self.validate()

    def is_c_var(self):
        return not self.is_function

    def validate(self):
        match self:
            case ImportStmt(is_c_var=True, args=[_, *_]):
                raise NodeError(
                    self, "function signatures only allowed when importing C or Python functions"
                )
            case ImportStmt(from_expr=IdExpr(value="C" | "python")):
                pass
            case _:
                head = self.from_expr
                while isinstance(head, DotExpr):
                    head = head.expr
                if head and not isinstance(head, IdExpr):
                    raise NodeError(head, "expected identifier")
                if self.what and not isinstance(self.what, IdExpr):
                    raise NodeError(self.what, "expected identifier")
                if self.args or self.ret:
                    raise NodeError(
                        self,
                        "function signatures only allowed when importing C or Python functions",
                    )


