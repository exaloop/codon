@dataclass(init=False)
class GeneratorExpr(Expr):
    class Kind(Enum):
        Generator = 0
        ListGenerator = 1
        SetGenerator = 2
        TupleGenerator = 3
        DictGenerator = 4

    kind: GeneratorExpr.Kind = Kind.Generator
    loops: object | None = None

    def __init__(
        self,
        kind: GeneratorExpr.Kind = Kind.Generator,
        loops: object | None = None,
        **kwargs,
    ):
        super().__init__(**kwargs)
        self.kind = kind
        self.loops = loops

    def iter_blocks(self, for_fn=None, if_fn=None, expr_fn=None):
        i = self.loops
        while True:
            match i:
                case ForStmt(suite=s):
                    if for_fn:
                        for_fn(i)
                    i = s
                case IfStmt(if_suite=s):
                    if if_fn:
                        if_fn(i)
                    i = s
                case SuiteStmt(items=[*_, ExprStmt(expr=e)]):
                    if expr_fn:
                        expr_fn(e)
                    return
                case SuiteStmt(items=[*_, s]):
                    i = s
                case _:
                    return

    def loop_count(self):
        cnt = 0

        def inc(s):
            nonlocal cnt
            cnt += 1

        self.iter_blocks(for_fn=inc, if_fn=inc)
        return cnt

    def final_expr(self):
        expr = None

        def catch(e):
            nonlocal expr
            expr = e

        self.iter_blocks(expr_fn=catch)
        return expr

    def final_suite(self):
        return self.loops


