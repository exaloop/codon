@dataclass(init=False)
class Param(Node):
    """Function signature parameter helper node (name: type = defaultValue)."""

    class Status(Enum):
        Value = 0
        Generic = 1
        HiddenGeneric = 2

    name: str = ""
    type: Expr | None = None
    default: Expr | None = None
    status: Param.Status = Status.Value

    def __init__(
        self,
        name: str = "",
        type: Expr | None = None,
        default: Expr | None = None,
        status: Param.Status = Status.Value,
        **kwargs,
    ):
        super().__init__(**kwargs)

        self.name = name
        self.type = type
        self.default = default
        self.status = status

        if self.status is Param.Status.Value:
            match self.type:
                case (
                    IdExpr(value="type" | "TypeTrait")
                    | IndexExpr(expr=IdExpr(value="TypeTrait"))
                ):
                    self.status = Param.Status.Generic
                case _:
                    static_kind = get_static_generic(self.type)
                    if static_kind is not Literal.Kind.Runtime:
                        self.status = Param.Status.Generic

    def is_value(self):
        return self.status is Param.Status.Value

    def is_generic(self):
        return self.status is Param.Status.Generic

    def is_hidden_generic(self):
        return self.status is Param.Status.HiddenGeneric

    def get_name_with_stars(self):
        stars = len(self.name) - len(self.name.lstrip("*"))
        return stars, self.name[stars:]


