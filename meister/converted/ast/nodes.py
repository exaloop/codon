@dataclass(init=False)
class SuiteStmt(Stmt):
    items: List[Stmt]

    def __init__(self, items: List[Stmt] | None = None, **kwargs):
        # C++ source: codon/parser/ast/stmt.cpp:35
        super().__init__(**kwargs)
        self.items = [] if items is None else items

    def first_in_block(self) -> Stmt | None:
        return None if not self.items else self.items[0].first_in_block()

    def flatten(self):
        flattened: List[Stmt] = []
        for item in self.items:
            if isinstance(item, SuiteStmt):
                flattened.extend(item.items)
            else:
                flattened.append(item)
        self.items = flattened

    def add(self, stmt: Stmt | None):
        if stmt is not None:
            self.items.append(stmt)
            self.done = self.done and stmt.done

    @staticmethod
    def wrap(stmt: Stmt | None) -> SuiteStmt | None:
        if stmt is None:
            return None
        return (
            stmt if isinstance(stmt, SuiteStmt) else SuiteStmt(items=[stmt], info=stmt)
        )


