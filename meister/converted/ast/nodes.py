class Node:
    """Base class for parser AST nodes."""

    @dataclass
    class SrcInfo:
        file: str = ""
        line: int = 0
        col: int = 0
        end_line: int = 0
        end_col: int = 0

    class Attribute:
        pass

    info: Node.SrcInfo
    attributes: Dict[Attr, Any | None]
    cache: object | None = None

    def __init__(
        self,
        info=None,
        attributes=None,
        cache=None,
        lineno=0,
        col_offset=0,
        end_lineno=0,
        end_col_offset=0,
    ):
        self.info = (
            Node.SrcInfo("", lineno, col_offset, end_lineno, end_col_offset)
            if info is None
            else (info.info if isinstance(info, Node) else info)
        )
        self.attributes = {} if attributes is None else attributes
        self.cache = cache

    def validate(self):
        pass

    @property
    def lineno(self):
        return self.info.line

    @property
    def col_offset(self):
        return self.info.col

    @property
    def end_lineno(self):
        return self.info.end_line

    @property
    def end_col_offset(self):
        return self.info.end_col

    def set(self, key: Attr, value=None):
        self.attributes[key] = value or True  # type: ignore

    def has(self, key: Attr):
        return key in self.attributes

    def get(self, key: Attr, default: Attribute | None = None):
        return self.attributes.get(key, default)

    def setdefault[T](self, key: Attr, default: T | None = None) -> T:
        return self.attributes.setdefault(key, default)  # type: ignore

    def erase(self, key: Attr):
        self.attributes.pop(key, None)

    _CODON_CLEAN = ".clean"

    def __deepcopy__(self, memo):
        cls = self.__class__
        result = cls.__new__(cls)
        memo[id(self)] = result
        clean = Node._CODON_CLEAN in memo
        for key, value in self.__dict__.items():
            if key in ("type", "expected_type"):
                setattr(result, key, None if clean else value)
            elif key == "done":
                setattr(result, key, False if clean else value)
            elif key in ("cache", "orig"):
                setattr(result, key, value)
            else:
                setattr(result, key, copy.deepcopy(value, memo))
        return result

    def clone(self, clean: bool = False):
        """Deep copy a node."""
        memo = {}
        if clean:
            memo[Node._CODON_CLEAN] = True
        return copy.deepcopy(self, memo)


class NodeError(Exception):
    info: Node.SrcInfo

    def __init__(self, info, msg):
        super().__init__(msg)
        if isinstance(info, Node) or (
            hasattr(info, "info") and isinstance(info.info, Node.SrcInfo)
        ):
            self.info = info.info
        else:
            assert isinstance(info, Node.SrcInfo), f"{info} {type(info)} is not SrcInfo"
            self.info = info


