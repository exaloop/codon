@dataclass(init=False)
class IntExpr(Expr):
    # Expression value is stored as a string that is parsed during typechecking.
    value: str = ""
    # Number suffix (e.g. "u" for "123u").
    suffix: str = ""
    # Parsed value and sign for "normal" 64-bit integers.
    int_value: int | None = None

    def __init__(
        self, value: str = "", suffix: str = "", int_value: int | None = None, **kwargs
    ):
        super().__init__(**kwargs)
        self.value = value
        self.suffix = suffix
        self.int_value = int_value

        if not self.value:
            if self.int_value is None:
                self.int_value = 0
            self.value = str(self.int_value)
        else:
            self.int_value = None
            self.value = self.value.replace("_", "")
            try:
                if self.value.startswith(("0b", "0B")):
                    self.int_value = int(self.value, 2)
                elif self.value.startswith(("0o", "0O")):
                    self.int_value = int(self.value, 8)
                elif self.value.startswith(("0x", "0X")):
                    self.int_value = int(self.value, 16)
                else:
                    self.int_value = int(self.value, 0)
                if self.int_value < 0 or self.int_value > (1 << 64) - 1:
                    self.int_value = None
            except ValueError:
                pass

    def has_stored_value(self):
        return self.int_value is not None

    def get_value(self) -> int:
        if self.int_value is None:
            raise ValueError("integer has not been parsed")
        return self.int_value

    def get_raw_data(self):
        return self.value, self.suffix


@dataclass(init=False)
class FloatExpr(Expr):
    # Expression value is stored as a string that is parsed during typechecking.
    value: str = ""
    # Number suffix (e.g. "u" for "123u").
    suffix: str = ""
    # Parsed value for 64-bit floats.
    float_value: float | None = None

    def __init__(
        self,
        value: str = "",
        suffix: str = "",
        float_value: float | None = None,
        **kwargs,
    ):
        super().__init__(**kwargs)
        self.value = value
        self.suffix = suffix
        self.float_value = float_value

        if not self.value:
            if self.float_value is None:
                self.float_value = 0.0
            self.value = f"{self.float_value:g}"
            return
        else:
            self.float_value = None
            self.value = self.value.replace("_", "")
            try:
                self.float_value = float(self.value)
            except ValueError:
                pass

    def has_stored_value(self):
        return self.float_value is not None

    def get_value(self) -> float:
        if self.float_value is None:
            raise ValueError("float has not been parsed")
        return self.float_value

    def get_raw_data(self):
        return self.value, self.suffix


@dataclass(init=False)
class StringExpr(Expr):
    @dataclass
    class FormatSpec:
        text: str = ""
        conversion: str = ""
        spec: str = ""

    @dataclass
    class String(Node):
        """Vector of {value, prefix} strings."""

        value: str = ""
        prefix: str = ""
        expr: Expr | None = None
        format: StringExpr.FormatSpec

        def __init__(
            self,
            value: str = "",
            prefix: str = "",
            expr: Expr | None = None,
            format: StringExpr.FormatSpec | None = None,
            **kwargs,
        ):
            super().__init__(**kwargs)
            self.value = value
            self.prefix = prefix
            self.expr = expr
            self.format = StringExpr.FormatSpec() if format is None else format

    strings: List[StringExpr.String]
    value: str = ""
    prefix: str = ""

    def __init__(
        self,
        strings: List[String] | None = None,
        value: str = "",
        prefix: str = "",
        **kwargs,
    ):
        super().__init__(**kwargs)
        self.strings = [] if strings is None else strings
        self.value = value
        self.prefix = prefix
        if not self.strings:
            self.strings = [StringExpr.String(value=self.value, prefix=self.prefix)]

    def __iter__(self) -> Iterator[String]:
        yield from self.strings

    @property
    def is_simple(self):
        return len(self.strings) == 1 and not self.strings[0].prefix

    def get_value(self) -> str:
        assert self.is_simple(), "invalid StringExpr"
        return self.strings[0].value


