@dataclass(init=False)
class CallExpr(Expr):
    @dataclass(init=False)
    class Arg(Node):
        name: str = ""
        value: Expr | None = None

        def __init__(self, name: str = "", value: Expr | None = None, **kwargs):
            super().__init__(**kwargs)
            self.name = name
            self.value = value
            if self.value is not None and self.info == Node.SrcInfo():
                self.info = self.value.info

    expr: Expr | None = None
    items: List[CallExpr.Arg]
    # True if type-checker has processed and re-ordered args.
    ordered: bool = False
    # True if the call is partial.
    partial: bool = False

    def __init__(
        self,
        expr: Expr | None = None,
        items: List | None = None,
        ordered: bool = False,
        partial: bool = False,
        **kwargs,
    ):
        super().__init__(**kwargs)
        self.items = []
        if items:
            for i in items:
                if isinstance(i, CallExpr.Arg):
                    self.items.append(i)
                else:
                    self.items.append(CallExpr.Arg("", i))
        self.expr = expr
        self.ordered = ordered
        self.partial = partial


