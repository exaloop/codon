def dump(
    node: Node,
    annotate_fields=True,
    include_attributes=False,
    indent: int | None = None,
):
    """
    Return a formatted dump of the tree in node.  This is mainly useful for
    debugging purposes.  If annotate_fields is true (by default),
    the returned string will show the names and the values for fields.
    If annotate_fields is false, the result string will be more compact by
    omitting unambiguous field names.  Attributes such as line
    numbers and column offsets are not dumped by default.  If this is wanted,
    include_attributes can be set to true.  If indent is a non-negative
    integer or string, then the tree will be pretty-printed with that indent
    level. None (the default) selects the single line representation.
    """

    from ...bridge import class_name

    def _format(node: Any, level=0):
        if indent:
            level += 1

        def format_items(items, simple=True, max_items=1, level=0):
            if indent:
                prefix = "\n" + (" " * indent) * level
                sep = ",\n" + (" " * indent) * level
            else:
                prefix = ""
                sep = ", "
            items = [i for i in items if i]
            if (simple and len(items) <= max_items) or not indent:
                return ", ".join(items), True
            return prefix + sep.join(items), False

        def format_args(node):
            if not hasattr(node, "attributes"):
                return "", True
            attrs = []
            allsimple = True
            for key, val in node.attributes.items():
                if isinstance(val, bool) and val:
                    attrs.append(key.name)
                else:
                    value, simple = _format(val, level + 2)
                    allsimple = allsimple and simple
                    if value:
                        attrs.append(f"{key.name}={value}")
                    else:
                        attrs.append(f"{key.name}")
            attrs.sort()
            if attrs:
                fs = format_items(attrs, allsimple, level=level + 1)
                return f"attrs=({fs[0]})", fs[1]
            return "", True

        if isinstance(node, SuiteStmt):
            if not node.items:
                return "", True
            args = []
            allsimple = True
            for i in node.items:
                value, simple = _format(i, level)
                args.append(value)
                allsimple = allsimple and simple
            if include_attributes:
                fs = format_args(node)
                args.append(fs[0])
                allsimple = allsimple and fs[1]
            fs = format_items(args, allsimple, level=level)
            return f"{'*' if node.done else ''}[{fs[0]}]", fs[1]
        elif isinstance(node, (Node, Node.Attribute, StringExpr.FormatSpec)):
            args = []
            allsimple = True
            for name, value in Codon.any_members(node):
                if name in ["attributes", "info", "done"]:
                    continue
                value, simple = _format(value, level)
                allsimple = allsimple and simple
                if annotate_fields and value:
                    args.append(f"{name}={value}")
                elif value:
                    args.append(value)
            if include_attributes:
                value, simple = format_args(node)
                allsimple = allsimple and simple
                args.append(value)
            args = [arg for arg in args if arg]

            name, braces = class_name(node), "()"
            if isinstance(node, SuiteStmt):
                name, braces = "", "[]"
            if hasattr(node, "done") and node.done:
                name += "*"
            if isinstance(node, StringExpr.FormatSpec) and not args:
                return "", True
            fs = format_items(args, allsimple, level=level)
            return f"{name}{braces[0]}{fs[0]}{braces[1]}", fs[1]
        if isinstance(node, Enum):
            return f"{node.name}", True
        if isinstance(node, str):
            return (f"{node!r}" if node else ""), True
        if isinstance(node, int):
            return f"{node}", True
        if isinstance(node, bool):
            return f"{node}", True
        else:
            if Any.is_tuple(node):
                fs = format_items(
                    [_format(x, level)[0] for x in cast(List[Any], node)], level=level
                )
                return f"({fs[0]})", fs[1]
            elif Any.is_list(node):
                n = cast(List[Any], node)
                if not n:
                    return "", True
                fs = format_items([_format(x, level)[0] for x in n], level=level)
                return f"[{fs[0]}]", fs[1]
            elif isinstance(node, dict):
                if not node:
                    return "", True
                fs = format_items(
                    [(repr(key) + "=" + _format(x, level)[0]) for key, x in sorted(node.items())],
                    level=level,
                )
                return f"{{{fs[0]}}}", fs[1]
            elif Any.is_optional(node):
                n = cast(Any | None, node)
                if n is None:
                    return "", True
                else:
                    if CODON:
                        return _format(Codon.unwrap(n), level)
                    else:
                        return repr(node), True
            return repr(node), True

    return _format(node)[0]


def iter_fields(node: Node) -> Iterator[Tuple[str, Any]]:
    """
    Yield a tuple of ``(fieldname, value)`` for each field in ``node._fields``
    that is present on *node*.
    """

    for name, value in Codon.any_members(node):
        node = value
        if (
            isinstance(value, Node)
            or Any.is_tuple(node)
            or Any.is_list(node)
            or Any.is_optional(node)
        ):
            yield name, node


def iter_child_nodes(node) -> Iterator[Node]:
    """
    Yield all direct child nodes of *node*, that is, all fields that are nodes
    and all items of fields that are lists of nodes.
    """

    def _get_node(a: Any) -> Any:
        if Any.is_optional(a):
            o = cast(Any | None, a)
            if o:
                return Codon.unwrap(o)
        return a

    for _, field in iter_fields(node):
        f = _get_node(field)
        if isinstance(f, Node):
            yield f
        elif Any.is_list(f):
            for item in cast(List[Any], f):
                i = _get_node(item)
                if isinstance(i, Node):
                    yield i


class NodeVisitor:
    def visit(self, node):
        """Visit a node."""

        method = "visit_" + node.__class__.__name__
        visitor = getattr(self, method, self.generic_visit)
        return visitor(node)

    def generic_visit(self, node):
        """Called if no explicit visitor function exists for a node."""

        for child in iter_child_nodes(node):
            self.visit(child)
